"""Emit structural Verilog mapped onto sky130_fd_sc_hd cells.

Every primitive gate maps to exactly one library cell (drive strength 1), so
the emitted netlist preserves the architecture: a synthesis tool is not
allowed to restructure it (the flow only sizes/buffers if asked).  Instance
names keep the functional group prefix ('pp_', 'red_', 'cpa_', 'acc_', 'reg_')
so that power reports can be split by group without double counting.
"""
from __future__ import annotations

from typing import Dict, List, Tuple

from .netlist import CONST0, CONST1, Netlist

PREFIX = "sky130_fd_sc_hd__"

# kind -> (cell, input pins, output pins)
CELLMAP: Dict[str, Tuple[str, Tuple[str, ...], Tuple[str, ...]]] = {
    "INV": ("inv_1", ("A",), ("Y",)),
    "BUF": ("buf_1", ("A",), ("X",)),
    "AND2": ("and2_1", ("A", "B"), ("X",)),
    "NAND2": ("nand2_1", ("A", "B"), ("Y",)),
    "OR2": ("or2_1", ("A", "B"), ("X",)),
    "NOR2": ("nor2_1", ("A", "B"), ("Y",)),
    "XOR2": ("xor2_1", ("A", "B"), ("X",)),
    "XNOR2": ("xnor2_1", ("A", "B"), ("Y",)),
    "AND3": ("and3_1", ("A", "B", "C"), ("X",)),
    "AO21": ("a21o_1", ("A1", "A2", "B1"), ("X",)),
    "AOI21": ("a21oi_1", ("A1", "A2", "B1"), ("Y",)),
    "OAI21": ("o21ai_1", ("A1", "A2", "B1"), ("Y",)),
    "MAJ3": ("maj3_1", ("A", "B", "C"), ("X",)),
    "XOR3": ("xor3_1", ("A", "B", "C"), ("X",)),
    "MUX2": ("mux2_1", ("A0", "A1", "S"), ("X",)),
    "HA": ("ha_1", ("A", "B"), ("SUM", "COUT")),
    "FA": ("fa_1", ("A", "B", "CIN"), ("SUM", "COUT")),
    "DFF": ("dfxtp_1", ("D",), ("Q",)),
}


def cellinfo(g) -> Tuple[str, Tuple[str, ...], Tuple[str, ...]]:
    """(cell name without prefix, input pins, output pins) of a gate."""
    if g.kind == "CELL":
        return g.cell, g.ip, g.op
    return CELLMAP[g.kind]


def cell_counts(nl: Netlist) -> Dict[str, int]:
    out: Dict[str, int] = {}
    for g in nl.gates:
        c = PREFIX + cellinfo(g)[0]
        out[c] = out.get(c, 0) + 1
    return out


def emit(nl: Netlist, module: str = None, clock: str = "clk") -> str:
    module = module or nl.name
    has_ff = any(g.kind == "DFF" for g in nl.gates)
    netname = {}
    for bus, nets in list(nl.inputs.items()) + list(nl.outputs.items()):
        pass
    # internal wire names
    for i in range(len(nl.nets)):
        netname[i] = f"n{i}"
    for bus, nets in nl.inputs.items():
        for k, n in enumerate(nets):
            netname[n] = f"{bus}[{k}]"
    ports = []
    decl = []
    if has_ff:
        ports.append(clock)
        decl.append(f"  input {clock};")
    for bus, nets in nl.inputs.items():
        ports.append(bus)
        decl.append(f"  input [{len(nets) - 1}:0] {bus};")
    for bus, nets in nl.outputs.items():
        ports.append(bus)
        decl.append(f"  output [{len(nets) - 1}:0] {bus};")
    lines = [f"// Generated by ugcal.arith.verilog from netlist '{nl.name}'",
             f"// meta: {nl.meta}",
             f"module {module} ({', '.join(ports)});"] + decl
    used = set()
    for g in nl.gates:
        used.update(g.ins)
        used.update(g.outs)
    for bus, nets in nl.outputs.items():
        used.update(nets)
    wires = sorted(n for n in used if n > CONST1 and not netname[n].count("["))
    for i in range(0, len(wires), 16):
        lines.append("  wire " + ", ".join(netname[n] for n in wires[i:i + 16]) + ";")

    def ref(n):
        if n == CONST0:
            return "1'b0"
        if n == CONST1:
            return "1'b1"
        return netname[n]

    for g in nl.gates:
        cell, ip, op = cellinfo(g)
        conns = []
        if g.kind == "DFF":
            conns.append(f".CLK({clock})")
        conns += [f".{p}({ref(n)})" for p, n in zip(ip, g.ins)]
        conns += [f".{p}({ref(n)})" for p, n in zip(op, g.outs)]
        lines.append(f"  {PREFIX}{cell} {g.name} ({', '.join(conns)});")
    for bus, nets in nl.outputs.items():
        for k, n in enumerate(nets):
            lines.append(f"  assign {bus}[{k}] = {ref(n)};")
    lines.append("endmodule")
    return "\n".join(lines) + "\n"
