#!/usr/bin/env python3
"""Write a reduced SKY130 SPICE model library for ngspice.

The full ``models/sky130.lib.spice`` loads every device in the PDK (about
18 s per ngspice run on the reference machine).  The HD standard cells use
only ``nfet_01v8`` and ``pfet_01v8_hvt`` (plus their ``special_`` wrappers,
defined in the same model files).  This script copies, for each process
corner, exactly the ``.include`` lines that ``models/corners/<corner>.spice``
uses for the selected device families, rewrites them to absolute paths and
adds the global options/parameters that the full library sets
(``.option scale=1.0u``, ``mc_mm_switch``, ``mc_pr_switch``, LOD parameters).

Nothing in the model cards is modified.  ``sim/spice/check_slim_lib.py``
verifies that the reduced library reproduces the full library's drain
currents bit-for-bit at a set of bias points.

Usage:  PDK_ROOT=~/pdk python3 sim/pdk/make_slim_lib.py [out_file]
"""
import os
import re
import sys

# section name -> (corner include file relative to models/, mismatch switch)
# The first five reproduce the sections of models/sky130.lib.spice of the same
# name; "tt_mm"/"ss_mm"/"ff_mm" enable the per-device mismatch terms
# (mc_mm_switch=1), as in sky130.lib.spice.  "leak" and "tt_leak" expose the
# corners/leak.spice and corners/tt/leak.spice model sets, which exist in the
# PDK but are not referenced by any section of sky130.lib.spice.
SECTIONS = {
    "tt": ("corners/tt.spice", 0), "ss": ("corners/ss.spice", 0), "ff": ("corners/ff.spice", 0),
    "sf": ("corners/sf.spice", 0), "fs": ("corners/fs.spice", 0),
    "tt_mm": ("corners/tt.spice", 1), "ss_mm": ("corners/ss.spice", 1), "ff_mm": ("corners/ff.spice", 1),
    "leak": ("corners/leak.spice", 0), "tt_leak": ("corners/tt/leak.spice", 0),
}
# Device families kept.  The first two are the ones the HD cells use; the
# others are kept for threshold-flavour comparisons in device sweeps.
FAMILIES = ("nfet_01v8", "pfet_01v8_hvt", "pfet_01v8", "nfet_01v8_lvt", "pfet_01v8_lvt")


def main() -> int:
    pdk_root = os.path.expanduser(os.environ.get("PDK_ROOT", "~/pdk"))
    fd_pr = os.path.join(pdk_root, "fd_pr")
    models = os.path.join(fd_pr, "models")
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "..", "..", "build", "sky130_slim.lib.spice")
    out = os.path.abspath(out)
    os.makedirs(os.path.dirname(out), exist_ok=True)

    lines = [
        "* Reduced SKY130 model library generated by sim/pdk/make_slim_lib.py",
        f"* Source: {fd_pr}",
        "* Device families: " + ", ".join(FAMILIES),
        "",
    ]
    for corner, (rel_file, mm) in SECTIONS.items():
        corner_file = os.path.join(models, rel_file)
        corner_dir = os.path.dirname(corner_file)
        lines.append(f".lib {corner}")
        lines.append(".option scale=1.0u")
        lines.append(f".param mc_mm_switch={mm}")
        lines.append(".param mc_pr_switch=0")
        lines.append(f'.include "{os.path.join(models, "parameters", "lod.spice")}"')
        with open(corner_file) as fh:
            for raw in fh:
                m = re.match(r'\s*\.include\s+"([^"]+)"', raw, re.I)
                if not m:
                    continue
                rel = m.group(1)
                parts = rel.split("/")
                # ../../cells/<family>/file
                if "cells" in parts:
                    fam = parts[parts.index("cells") + 1]
                    if fam in FAMILIES:
                        lines.append(f'.include "{os.path.normpath(os.path.join(corner_dir, rel))}"')
        lines.append(f".endl {corner}")
        lines.append("")
    with open(out, "w") as fh:
        fh.write("\n".join(lines))
    print(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
