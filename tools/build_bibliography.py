#!/usr/bin/env python3
"""Render docs/report/D15_bibliography.md from data/sources.yaml (requires PyYAML)."""
import os

import yaml

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
CATS = {
    "A": "A. Thermodynamics of computation and fundamental constants",
    "B": "B. Semiconductor device physics",
    "C": "C. Compact transistor models",
    "D": "D. Foundry documentation, PDKs and predictive kits",
    "E": "E. Circuit design: arithmetic and low-power logic",
    "F": "F. Physical design, analysis tools, standards and inputs",
    "G": "G. AI accelerator architecture and data movement",
    "H": "H. Thermal engineering and reliability",
}
ACCESS = {
    "file": "file read at a pinned commit",
    "code": "source code / tool used at a pinned version",
    "search": "bibliographic data and abstract-level content confirmed via a search service; full text not opened",
    "restricted": "requires licence, registration or NDA; not inspected",
    "input-file": "cited in the input research file; not re-verified",
}
KIND = {
    "peer-reviewed-experimental": "measured data (peer-reviewed)",
    "peer-reviewed-theoretical": "theory / analysis (peer-reviewed)",
    "foundry-supplied": "foundry data",
    "open-pdk": "open PDK documentation",
    "compact-model-doc": "compact-model documentation",
    "open-source-code": "software / repository",
    "standard": "standard",
    "book": "book",
    "secondary": "secondary / compilation",
    "predictive": "predictive model or kit",
}


def esc(x):
    return str(x).replace("|", "\\|").replace("\n", " ")


def main():
    src = yaml.safe_load(open(os.path.join(ROOT, "data", "sources.yaml")))
    out = ["# D15 — Bibliography and source catalogue", "",
           "Generated by `tools/build_bibliography.py` from `data/sources.yaml`; edit the YAML, not this file.", "",
           "**Access legend.** " + "; ".join(f"*{k}*: {v}" for k, v in ACCESS.items()) + ".", "",
           "No DOI is listed unless a search result or the publisher record confirmed it in this session; entries "
           "without a DOI are identified by venue, volume and pages. Publisher sites, arXiv, readthedocs, nist.gov and "
           "bsim.berkeley.edu were not reachable from the container, so no paper's full text was opened. "
           "Statements attributed to papers are limited to what abstracts and search summaries support, "
           "and quantitative details seen only in secondary sources are marked as such where used.", "",
           f"{len(src)} entries. Counts by access: " +
           ", ".join(f"{k} {sum(1 for s in src if s['access'] == k)}" for k in ACCESS) + ".", ""]
    for c, title in CATS.items():
        items = [s for s in src if s.get("cat") == c]
        if not items:
            continue
        out += [f"## {title}", ""]
        for s in sorted(items, key=lambda s: (str(s.get("date", "")), s["id"])):
            ref = f"**[{s['id']}]** {esc(s.get('authors', ''))}. *{esc(s['title'])}*."
            if s.get("venue"):
                ref += f" {esc(s['venue'])}."
            if s.get("date"):
                ref += f" {s['date']}."
            if s.get("version"):
                ref += f" Version: {esc(s['version'])}."
            if s.get("doi"):
                ref += f" doi:{s['doi']}."
            if s.get("url"):
                ref += f" <{s['url']}>"
            out.append(ref)
            out.append("")
            out.append(f"* Kind: {KIND.get(s.get('kind'), s.get('kind'))}. Access: {ACCESS.get(s['access'], s['access'])}.")
            if s.get("location"):
                out.append(f"* Location used: {esc(s['location'])}")
            if s.get("supports"):
                out.append(f"* Supports: {esc(s['supports'])}")
            if s.get("limits"):
                out.append(f"* Limits / supersession: {esc(s['limits'])}")
            out.append("")
    open(os.path.join(ROOT, "docs", "report", "D15_bibliography.md"), "w").write("\n".join(out))
    print(f"wrote D15 with {len(src)} entries")


if __name__ == "__main__":
    main()
